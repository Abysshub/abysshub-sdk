import assert from "node:assert/strict";
import { readFile } from "node:fs/promises";
import { join } from "node:path";
import { test } from "node:test";
import { Abyss, AbyssError, FilesAsleepError } from "../dist/index.js";
import { Run } from "../dist/run.js";
import { callerInput, perform, skipPauses, timeoutOnceHeld, withFiles } from "./caller.js";
import { loadExchanges, pattern, replay } from "./fake-server.js";

const KEY = "abyss_sk_fake_for_tests";

skipPauses();

/** The codes `run.save()` raises as `FilesAsleepError`. */
const FILES_ASLEEP = new Set(["files_asleep", "files_waking"]);

// The fields `expected` names, however deep: a list must have its length, and an
// object at least the fields it names.
function assertFields(actual, expected, where) {
  if (Array.isArray(expected)) {
    assert.ok(Array.isArray(actual), `${where} is a list`);
    assert.equal(actual.length, expected.length, `${where}.length`);
    expected.forEach((item, index) => assertFields(actual[index], item, `${where}[${index}]`));
  } else if (expected && typeof expected === "object") {
    assert.ok(actual && typeof actual === "object", `${where} is an object`);
    for (const [name, value] of Object.entries(expected)) assertFields(actual[name], value, `${where}.${name}`);
  } else {
    assert.equal(actual, expected, where);
  }
}

for (const recording of await loadExchanges()) {
  const { method = "run", input = {}, files = {}, save, wake, client = {} } = recording.call;
  test(`${method}(): ${recording.name}`, async () => {
    const server = await replay(recording, { key: KEY });
    try {
      await withFiles(files, async (dir) => {
        const abyss = new Abyss({ apiKey: KEY, baseURL: server.base, maxRetries: client.max_retries });
        // A timeout that ends a hold runs out only once the server holds.
        const call = () => perform(abyss, recording.call, callerInput(input, dir, files));
        const holds = recording.call.options?.timeout && recording.exchanges.some(({ response }) => response.hold);
        const outcome = await (holds ? timeoutOnceHeld(server.held, call) : call()).then(
          (value) => ({ value }),
          (error) => ({ error }),
        );
        const saving =
          save && outcome.value
            ? await outcome.value.save(join(dir, save)).then((paths) => ({ paths }), (error) => ({ error }))
            : {};
        if (saving.error && !recording.outcome.save_error) throw saving.error;
        const saved = saving.paths ?? null;
        const woken = wake && outcome.value ? await outcome.value.wake() : null;

        assert.deepEqual(server.problems, []);
        assert.equal(server.remaining(), 0, "every recorded request was sent");
        if (recording.outcome.run) {
          assert.ok(outcome.value instanceof Run, `expected a run, got ${outcome.error ?? outcome.value}`);
          assertFields(outcome.value, recording.outcome.run, "run");
        } else if (recording.outcome.value) {
          assert.ok(outcome.value, `expected a value, got ${outcome.error}`);
          assertFields(outcome.value, recording.outcome.value, "value");
        } else {
          assert.ok(outcome.error instanceof AbyssError, `expected an AbyssError, got ${outcome.error ?? outcome.value}`);
          const { run, ...fields } = recording.outcome.error;
          assertFields(outcome.error, fields, "error");
          if (run === null) assert.equal(outcome.error.run, null);
          else assertFields(outcome.error.run, run, "error.run");
        }
        if (recording.outcome.save_error) {
          const { code } = recording.outcome.save_error;
          assert.ok(saving.error instanceof AbyssError, `expected run.save() to raise, got ${saving.paths}`);
          assert.equal(saving.error instanceof FilesAsleepError, FILES_ASLEEP.has(code), "the files-asleep error");
          assertFields(saving.error, recording.outcome.save_error, "save_error");
        }
        if (recording.outcome.woken) {
          assert.ok(woken instanceof Run, `expected run.wake() to answer a run, got ${woken}`);
          assertFields(woken, recording.outcome.woken, "woken");
        }
        if (recording.outcome.saved) {
          const expected = Object.keys(recording.outcome.saved).map((path) => join(dir, save, path));
          assert.deepEqual(saved, expected, "run.save() answers the paths it wrote");
          // A saved `pattern` is a whole file of that many generated bytes.
          for (const [path, content] of Object.entries(recording.outcome.saved)) {
            const bytes = await readFile(join(dir, save, path));
            if (content.pattern) assert.ok(bytes.equals(pattern(0, content.pattern - 1)), `saved ${path}`);
            else assert.equal(bytes.toString("utf8"), content, `saved ${path}`);
          }
        }
      });
    } finally {
      await server.close();
    }
  });
}
